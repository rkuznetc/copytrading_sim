# src/copytrading_sim/simulator/compatibility.py

from __future__ import annotations

from typing import Any

import numpy as np
import pandas as pd


HORIZON_ORDER = {
    "short": 0,
    "medium": 1,
    "long": 2,
}

EXPERIENCE_TO_SCORE = {
    "beginner": 0.25,
    "intermediate": 0.50,
    "advanced": 0.80,
}

DEFAULT_COMPATIBILITY_WEIGHTS = {
    "risk": 0.30,
    "drawdown": 0.25,
    "horizon": 0.15,
    "asset": 0.15,
    "complexity": 0.15,
}

REQUIRED_USER_COLUMNS = {
    "user_id",
    "risk_tolerance",
    "drawdown_tolerance",
    "investment_horizon",
    "preferred_asset_class",
    "experience_level",
}

REQUIRED_STRATEGY_COLUMNS = {
    "strategy_id",
    "risk_score",
    "max_drawdown_proxy",
    "horizon_type",
    "main_asset_class",
    "complexity_score",
}


def compute_compatibility(
    users: pd.DataFrame,
    strategies: pd.DataFrame,
    weights: dict[str, float] | None = None,
    top_k: int | None = None,
) -> pd.DataFrame:
    """Compute interpretable user-strategy compatibility.

    Parameters
    ----------
    users:
        User profiles generated by user_generator.generate_users.
    strategies:
        Strategy profiles generated by strategy_generator.generate_strategies.
    weights:
        Optional weights for compatibility components.
    top_k:
        If provided, return only top_k strategies per user by compatibility_score.

    Returns
    -------
    pd.DataFrame
        Long table with user_id, strategy_id, component scores and final compatibility_score.
    """
    _validate_input_columns(users, strategies)

    if weights is None:
        weights = DEFAULT_COMPATIBILITY_WEIGHTS

    _validate_weights(weights)

    records: list[pd.DataFrame] = []

    strategy_ids = strategies["strategy_id"].to_numpy()
    strategy_risk = strategies["risk_score"].to_numpy(dtype=float)
    strategy_drawdown = strategies["max_drawdown_proxy"].to_numpy(dtype=float)
    strategy_horizon = strategies["horizon_type"].astype(str).to_numpy()
    strategy_asset = strategies["main_asset_class"].astype(str).to_numpy()
    strategy_complexity = strategies["complexity_score"].to_numpy(dtype=float)

    strategy_type = (
        strategies["strategy_type"].astype(str).to_numpy()
        if "strategy_type" in strategies.columns
        else np.array(["unknown"] * len(strategies))
    )
    strategy_popularity = (
        strategies["popularity_score"].to_numpy(dtype=float)
        if "popularity_score" in strategies.columns
        else np.full(len(strategies), np.nan)
    )

    for _, user in users.iterrows():
        user_id = user["user_id"]

        risk_match = 1.0 - np.abs(float(user["risk_tolerance"]) - strategy_risk)
        drawdown_match = 1.0 - np.abs(float(user["drawdown_tolerance"]) - strategy_drawdown)

        horizon_match = np.array(
            [
                _horizon_match(str(user["investment_horizon"]), str(horizon))
                for horizon in strategy_horizon
            ],
            dtype=float,
        )

        asset_match = np.array(
            [
                _asset_match(str(user["preferred_asset_class"]), str(asset))
                for asset in strategy_asset
            ],
            dtype=float,
        )

        user_experience_score = _experience_score(str(user["experience_level"]))
        complexity_match = 1.0 - np.abs(user_experience_score - strategy_complexity)

        compatibility_score = (
            weights["risk"] * risk_match
            + weights["drawdown"] * drawdown_match
            + weights["horizon"] * horizon_match
            + weights["asset"] * asset_match
            + weights["complexity"] * complexity_match
        )
        compatibility_score = np.clip(compatibility_score, 0.0, 1.0)

        user_type = str(user["user_type"]) if "user_type" in users.columns else "unknown"

        records.append(
            pd.DataFrame(
                {
                    "user_id": user_id,
                    "strategy_id": strategy_ids,
                    "user_type": user_type,
                    "strategy_type": strategy_type,
                    "risk_match": risk_match,
                    "drawdown_match": drawdown_match,
                    "horizon_match": horizon_match,
                    "asset_match": asset_match,
                    "complexity_match": complexity_match,
                    "compatibility_score": compatibility_score,
                    "strategy_risk_score": strategy_risk,
                    "strategy_max_drawdown_proxy": strategy_drawdown,
                    "strategy_popularity_score": strategy_popularity,
                }
            )
        )

    compatibility = pd.concat(records, ignore_index=True)

    if top_k is not None:
        if top_k <= 0:
            raise ValueError("top_k must be positive when provided.")

        compatibility = (
            compatibility.sort_values(
                by=["user_id", "compatibility_score"],
                ascending=[True, False],
            )
            .groupby("user_id", as_index=False, sort=False)
            .head(top_k)
            .reset_index(drop=True)
        )

    return compatibility


def _validate_input_columns(
    users: pd.DataFrame,
    strategies: pd.DataFrame,
) -> None:
    """Validate required user and strategy columns."""
    missing_user_columns = REQUIRED_USER_COLUMNS - set(users.columns)
    missing_strategy_columns = REQUIRED_STRATEGY_COLUMNS - set(strategies.columns)

    if missing_user_columns:
        raise ValueError(f"Missing user columns: {sorted(missing_user_columns)}")

    if missing_strategy_columns:
        raise ValueError(f"Missing strategy columns: {sorted(missing_strategy_columns)}")


def _validate_weights(weights: dict[str, float]) -> None:
    """Validate compatibility weights."""
    expected = set(DEFAULT_COMPATIBILITY_WEIGHTS)
    actual = set(weights)

    if actual != expected:
        raise ValueError(
            f"Compatibility weights must have keys {sorted(expected)}, got {sorted(actual)}"
        )

    total = sum(weights.values())

    if not np.isclose(total, 1.0):
        raise ValueError(f"Compatibility weights must sum to 1.0, got {total:.4f}")

    if any(value < 0 for value in weights.values()):
        raise ValueError("Compatibility weights must be non-negative.")


def _horizon_match(user_horizon: str, strategy_horizon: str) -> float:
    """Match user horizon and strategy horizon."""
    if user_horizon not in HORIZON_ORDER:
        raise ValueError(f"Unknown user horizon: {user_horizon}")

    if strategy_horizon not in HORIZON_ORDER:
        raise ValueError(f"Unknown strategy horizon: {strategy_horizon}")

    distance = abs(HORIZON_ORDER[user_horizon] - HORIZON_ORDER[strategy_horizon])

    if distance == 0:
        return 1.0

    if distance == 1:
        return 0.5

    return 0.0


def _asset_match(
    preferred_asset_class: str,
    strategy_asset_class: str,
) -> float:
    """Match preferred user asset class and main strategy asset class."""
    if preferred_asset_class == strategy_asset_class:
        return 1.0

    if preferred_asset_class == "mixed" or strategy_asset_class == "mixed":
        return 0.5

    return 0.0


def _experience_score(experience_level: str) -> float:
    """Map categorical experience level into strategy complexity tolerance."""
    if experience_level not in EXPERIENCE_TO_SCORE:
        raise ValueError(f"Unknown experience level: {experience_level}")

    return EXPERIENCE_TO_SCORE[experience_level]