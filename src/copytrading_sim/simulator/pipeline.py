from __future__ import annotations

from typing import Any

import numpy as np
import pandas as pd

from copytrading_sim.simulator.compatibility import compute_compatibility
from copytrading_sim.simulator.copy_decision import (
    build_copy_events,
    simulate_copy_decisions,
)
from copytrading_sim.simulator.exposure_policy import generate_exposures
from copytrading_sim.simulator.strategy_generator import generate_strategies
from copytrading_sim.simulator.user_generator import generate_users


SimulationTables = dict[str, pd.DataFrame]


def run_pipeline(
    config: dict[str, Any],
    rng: np.random.Generator | None = None,
) -> SimulationTables:
    """Run the current MVP simulation pipeline.

    Pipeline:
    1. Generate users.
    2. Generate strategies.
    3. Compute true interpretable compatibility.
    4. Generate logged exposures with a behavior policy.
    5. Simulate copy decisions from shown strategies.

    Returns
    -------
    dict[str, pd.DataFrame]
        Tables generated by the simulator.
    """
    if rng is None:
        seed = int(config["random"]["seed"])
        rng = np.random.default_rng(seed)

    users = generate_users(config=config, rng=rng)
    strategies = generate_strategies(config=config, rng=rng)

    compatibility = compute_compatibility(
        users=users,
        strategies=strategies,
        top_k=None,
    )

    exposures = generate_exposures(
        users=users,
        strategies=strategies,
        compatibility=compatibility,
        config=config,
        rng=rng,
    )

    copy_decisions = simulate_copy_decisions(
        exposures=exposures,
        config=config,
        rng=rng,
    )

    copy_events = build_copy_events(copy_decisions)

    metadata = build_metadata(
        config=config,
        users=users,
        strategies=strategies,
        compatibility=compatibility,
        exposures=exposures,
        copy_decisions=copy_decisions,
        copy_events=copy_events,
    )

    return {
        "users": users,
        "strategies": strategies,
        "compatibility": compatibility,
        "exposures": exposures,
        "copy_decisions": copy_decisions,
        "copy_events": copy_events,
        "metadata": metadata,
    }


def build_metadata(
    config: dict[str, Any],
    users: pd.DataFrame,
    strategies: pd.DataFrame,
    compatibility: pd.DataFrame,
    exposures: pd.DataFrame,
    copy_decisions: pd.DataFrame,
    copy_events: pd.DataFrame,
) -> pd.DataFrame:
    """Build one-row metadata table for the simulation run."""
    n_users = len(users)
    n_strategies = len(strategies)
    n_exposures = len(exposures)
    n_copy_events = len(copy_events)

    copy_rate = (
        float(copy_decisions["copied"].mean())
        if len(copy_decisions) > 0 and "copied" in copy_decisions.columns
        else 0.0
    )

    return pd.DataFrame(
        [
            {
                "project_name": config.get("project", {}).get("name", "unknown"),
                "project_version": config.get("project", {}).get("version", "unknown"),
                "seed": int(config["random"]["seed"]),
                "n_users": n_users,
                "n_strategies": n_strategies,
                "n_compatibility_rows": len(compatibility),
                "n_exposure_rows": n_exposures,
                "n_copy_events": n_copy_events,
                "copy_rate_per_exposed_item": copy_rate,
                "exposures_per_user": int(config["simulation"]["exposures_per_user"]),
                "slate_size": int(config["simulation"]["slate_size"]),
            }
        ]
    )