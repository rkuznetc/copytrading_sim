# src/copytrading_sim/simulator/exposure_policy.py

from __future__ import annotations

from typing import Any

import numpy as np
import pandas as pd


DEFAULT_EXPOSURE_POLICY_PARAMS = {
    "policy_name": "compatibility_popularity_mixed",
    "compatibility_weight": 0.65,
    "popularity_weight": 0.25,
    "social_popularity_weight": 0.10,
    "noise_std": 0.05,
    "temperature": 0.25,
}

REQUIRED_COMPATIBILITY_COLUMNS = {
    "user_id",
    "strategy_id",
    "compatibility_score",
    "risk_match",
    "drawdown_match",
    "horizon_match",
    "asset_match",
    "complexity_match",
}

REQUIRED_USER_COLUMNS = {
    "user_id",
    "risk_tolerance",
    "drawdown_tolerance",
    "investment_horizon",
    "preferred_asset_class",
    "experience_level",
    "social_sensitivity",
}

REQUIRED_STRATEGY_COLUMNS = {
    "strategy_id",
    "risk_score",
    "max_drawdown_proxy",
    "return_proxy",
    "popularity_score",
    "main_asset_class",
    "horizon_type",
    "complexity_score",
}


def generate_exposures(
    users: pd.DataFrame,
    strategies: pd.DataFrame,
    compatibility: pd.DataFrame,
    config: dict[str, Any],
    rng: np.random.Generator | None = None,
) -> pd.DataFrame:
    """Generate logged exposure events.

    Each user receives several slates of strategies.
    Exposure is generated by a behavior policy, not by pure compatibility.
    This is important because logged copy-trading data should contain
    platform/social visibility bias.
    """
    _validate_inputs(users, strategies, compatibility)

    if rng is None:
        seed = int(config["random"]["seed"])
        rng = np.random.default_rng(seed)

    params = _get_exposure_policy_params(config)

    exposures_per_user = int(config["simulation"]["exposures_per_user"])
    slate_size = int(config["simulation"]["slate_size"])

    if slate_size <= 0:
        raise ValueError("simulation.slate_size must be positive.")

    if slate_size > len(strategies):
        raise ValueError(
            f"slate_size={slate_size} cannot be greater than n_strategies={len(strategies)}"
        )

    candidates = _build_candidate_table(
        users=users,
        strategies=strategies,
        compatibility=compatibility,
    )

    all_slates: list[pd.DataFrame] = []

    for user_id, user_candidates in candidates.groupby("user_id", sort=False):
        user_candidates = user_candidates.reset_index(drop=True)

        for timestamp_step in range(exposures_per_user):
            slate_id = f"user_{user_id}_step_{timestamp_step}"

            slate = _sample_slate_plackett_luce(
                candidates=user_candidates,
                slate_size=slate_size,
                slate_id=slate_id,
                timestamp_step=timestamp_step,
                params=params,
                rng=rng,
            )
            all_slates.append(slate)

    exposures = pd.concat(all_slates, ignore_index=True)

    exposures.insert(0, "exposure_id", np.arange(len(exposures), dtype=int))
    exposures["was_shown"] = 1
    exposures["policy_name"] = params["policy_name"]

    ordered_columns = [
        "exposure_id",
        "slate_id",
        "user_id",
        "strategy_id",
        "timestamp_step",
        "position",
        "was_shown",
        "policy_name",
        "logging_score",
        "position_probability",
        "slate_probability_prefix",
        "compatibility_score",
        "strategy_popularity_score",
        "social_sensitivity",
        "risk_match",
        "drawdown_match",
        "horizon_match",
        "asset_match",
        "complexity_match",
        "user_type",
        "strategy_type",
        "risk_tolerance",
        "drawdown_tolerance",
        "investment_horizon",
        "preferred_asset_class",
        "experience_level",
        "liquidity_need",
        "strategy_risk_score",
        "strategy_max_drawdown_proxy",
        "strategy_return_proxy",
        "strategy_horizon_type",
        "strategy_main_asset_class",
        "strategy_complexity_score",
    ]

    existing_ordered_columns = [col for col in ordered_columns if col in exposures.columns]
    remaining_columns = [col for col in exposures.columns if col not in existing_ordered_columns]

    return exposures[existing_ordered_columns + remaining_columns]


def _build_candidate_table(
    users: pd.DataFrame,
    strategies: pd.DataFrame,
    compatibility: pd.DataFrame,
) -> pd.DataFrame:
    """Merge users, strategies and compatibility into candidate table."""
    compatibility_cols = [
        "user_id",
        "strategy_id",
        "compatibility_score",
        "risk_match",
        "drawdown_match",
        "horizon_match",
        "asset_match",
        "complexity_match",
    ]

    user_cols = [
        "user_id",
        "risk_tolerance",
        "drawdown_tolerance",
        "investment_horizon",
        "preferred_asset_class",
        "experience_level",
        "social_sensitivity",
    ]

    optional_user_cols = ["user_type", "liquidity_need"]
    user_cols += [col for col in optional_user_cols if col in users.columns]

    strategy_cols = [
        "strategy_id",
        "risk_score",
        "max_drawdown_proxy",
        "return_proxy",
        "popularity_score",
        "main_asset_class",
        "horizon_type",
        "complexity_score",
    ]

    optional_strategy_cols = ["strategy_type"]
    strategy_cols += [col for col in optional_strategy_cols if col in strategies.columns]

    candidates = (
        compatibility[compatibility_cols]
        .merge(users[user_cols], on="user_id", how="left")
        .merge(strategies[strategy_cols], on="strategy_id", how="left")
    )

    candidates = candidates.rename(
        columns={
            "risk_score": "strategy_risk_score",
            "max_drawdown_proxy": "strategy_max_drawdown_proxy",
            "return_proxy": "strategy_return_proxy",
            "popularity_score": "strategy_popularity_score",
            "main_asset_class": "strategy_main_asset_class",
            "horizon_type": "strategy_horizon_type",
            "complexity_score": "strategy_complexity_score",
        }
    )

    if "user_type" not in candidates.columns:
        candidates["user_type"] = "unknown"

    if "strategy_type" not in candidates.columns:
        candidates["strategy_type"] = "unknown"

    if "liquidity_need" not in candidates.columns:
        candidates["liquidity_need"] = "medium"

    return candidates


def _sample_slate_plackett_luce(
    candidates: pd.DataFrame,
    slate_size: int,
    slate_id: str,
    timestamp_step: int,
    params: dict[str, float | str],
    rng: np.random.Generator,
) -> pd.DataFrame:
    """Sample an ordered slate using a Plackett-Luce-like procedure.

    The recorded position_probability is the probability of selecting
    the chosen item at its position, conditional on previous choices.
    """
    remaining = candidates.copy().reset_index(drop=True)

    logging_scores = _compute_logging_scores(
        candidates=remaining,
        params=params,
        rng=rng,
    )
    remaining["logging_score"] = logging_scores

    selected_rows: list[pd.Series] = []
    slate_probability_prefix = 1.0

    temperature = float(params["temperature"])

    for position in range(1, slate_size + 1):
        probabilities = _softmax(
            remaining["logging_score"].to_numpy(dtype=float),
            temperature=temperature,
        )

        local_index = int(rng.choice(np.arange(len(remaining)), p=probabilities))
        selected = remaining.iloc[local_index].copy()

        position_probability = float(probabilities[local_index])
        slate_probability_prefix *= position_probability

        selected["slate_id"] = slate_id
        selected["timestamp_step"] = timestamp_step
        selected["position"] = position
        selected["position_probability"] = position_probability
        selected["slate_probability_prefix"] = slate_probability_prefix

        selected_rows.append(selected)

        remaining = remaining.drop(index=remaining.index[local_index]).reset_index(drop=True)

    return pd.DataFrame(selected_rows)


def _compute_logging_scores(
    candidates: pd.DataFrame,
    params: dict[str, float | str],
    rng: np.random.Generator,
) -> np.ndarray:
    """Compute behavior-policy scores for exposure generation."""
    compatibility = candidates["compatibility_score"].to_numpy(dtype=float)
    popularity = candidates["strategy_popularity_score"].to_numpy(dtype=float)
    social_sensitivity = candidates["social_sensitivity"].to_numpy(dtype=float)

    noise = rng.normal(
        loc=0.0,
        scale=float(params["noise_std"]),
        size=len(candidates),
    )

    logging_score = (
        float(params["compatibility_weight"]) * compatibility
        + float(params["popularity_weight"]) * popularity
        + float(params["social_popularity_weight"]) * social_sensitivity * popularity
        + noise
    )

    return np.clip(logging_score, 0.0, 1.0)


def _softmax(scores: np.ndarray, temperature: float) -> np.ndarray:
    """Stable softmax with temperature."""
    if temperature <= 0:
        raise ValueError("temperature must be positive.")

    scaled = scores / temperature
    scaled = scaled - np.max(scaled)
    exp_scores = np.exp(scaled)
    total = exp_scores.sum()

    if total <= 0 or not np.isfinite(total):
        return np.full(len(scores), 1.0 / len(scores))

    return exp_scores / total


def _get_exposure_policy_params(config: dict[str, Any]) -> dict[str, float | str]:
    """Read exposure policy params from config or use defaults.

    Supported optional config section:

    exposure_policy:
      policy_name: "compatibility_popularity_mixed"
      compatibility_weight: 0.65
      popularity_weight: 0.25
      social_popularity_weight: 0.10
      noise_std: 0.05
      temperature: 0.25
    """
    params = DEFAULT_EXPOSURE_POLICY_PARAMS.copy()
    params.update(config.get("exposure_policy", {}))

    numeric_keys = [
        "compatibility_weight",
        "popularity_weight",
        "social_popularity_weight",
        "noise_std",
        "temperature",
    ]

    for key in numeric_keys:
        params[key] = float(params[key])

    total_weight = (
        float(params["compatibility_weight"])
        + float(params["popularity_weight"])
        + float(params["social_popularity_weight"])
    )

    if not np.isclose(total_weight, 1.0):
        raise ValueError(
            "Exposure policy weights must sum to 1.0: "
            f"got {total_weight:.4f}"
        )

    if float(params["temperature"]) <= 0:
        raise ValueError("exposure_policy.temperature must be positive.")

    if float(params["noise_std"]) < 0:
        raise ValueError("exposure_policy.noise_std must be non-negative.")

    return params


def _validate_inputs(
    users: pd.DataFrame,
    strategies: pd.DataFrame,
    compatibility: pd.DataFrame,
) -> None:
    """Validate required input columns."""
    missing_user_columns = REQUIRED_USER_COLUMNS - set(users.columns)
    missing_strategy_columns = REQUIRED_STRATEGY_COLUMNS - set(strategies.columns)
    missing_compatibility_columns = REQUIRED_COMPATIBILITY_COLUMNS - set(compatibility.columns)

    if missing_user_columns:
        raise ValueError(f"Missing user columns: {sorted(missing_user_columns)}")

    if missing_strategy_columns:
        raise ValueError(f"Missing strategy columns: {sorted(missing_strategy_columns)}")

    if missing_compatibility_columns:
        raise ValueError(
            f"Missing compatibility columns: {sorted(missing_compatibility_columns)}"
        )